"""A draft URDF built from robot.json (the same numbers, converted to SI).

The file is a starting point for a human, not a robot model to trust. It has no meshes, link
frames are parallel to the file's axes, every joint is at zero in the stored pose, masses are
estimates (and absent when no material is known), and a joint limit is written only when the
designer gave one in design_context.yaml.
"""

from __future__ import annotations

import math
import re
from typing import Any
from xml.sax.saxutils import quoteattr

from stepscribe.models.schema import Report
from stepscribe.pack.robot import build_robot

DRAFT = "Draft generated by stepscribe from geometry. Needs human verification."
MM = 1e-3  # mm to m
G = 1e-3  # g to kg
INERTIA = 1e-9  # g*mm^2 to kg*m^2


def _n(v: float) -> str:
    return f"{v:.9g}"


def _xyz(v: list[float], scale: float = MM) -> str:
    return " ".join(_n(x * scale) for x in v)


def _c(text: str) -> str:
    """Text that is safe inside an XML comment (no double hyphen, no closing sequence)."""
    return re.sub(r"-{2,}", "-", text.replace("--", "- -")).replace(">", "&gt;")


def _name(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", text).strip("_") or "robot"


def _header(robot: dict[str, Any]) -> list[str]:
    lines = [
        DRAFT,
        f"Source: {robot['source']}",
        "Pose: every joint is at zero in the pose stored in the file; link frames are parallel to the",
        "file's axes (rpy 0); each link frame sits on the origin of the joint that carries it.",
        "Units: metres, kilograms, radians (the source numbers are mm, g, degrees).",
        "There is no visual or collision geometry in this file.",
        "Mass and inertia are estimates from CAD volume and an assumed density, not measurements.",
        "Vendor robot models are often hollow or simplified shells: mass taken from them is not reliable.",
        "A revolute joint needs a lower/upper limit in URDF (they default to 0, which locks it). Where",
        "none is known the joint is written as type continuous, with no limit element, and a comment;",
        "change it to revolute and add the real limit (design_context.yaml: kinematics: joints: range).",
        "Effort and velocity are not known for any joint: they are written as 0 where a limit exists.",
        "",
        "DH-style table (a, d in mm, alpha in degrees, between consecutive joint axes):",
    ]
    rows = robot["dh_style"]["rows"]
    for r in rows:
        lines.append(
            f"  {r['joint']}: a={_n(r['a_mm'])}  alpha={_n(r['alpha_deg'])}  d={_n(r['d_mm'])}"
        )
    if not rows:
        lines.append("  (not a single serial chain from the base: no table)")
    # an XML comment cannot hold a double hyphen, so the command-line flag is named in words
    warnings = [w.replace("--material", "the material option") for w in robot["warnings"]]
    lines += ["", "Warnings:"] + [f"  - {w}" for w in warnings]
    return [_c(x) for x in lines]


def build_urdf(robot: dict[str, Any] | None) -> str:
    """URDF text for a robot.json dict."""
    if robot is None:
        raise ValueError("not a robot: nothing to write")
    base = robot["base_link"]
    frame: dict[str, list[float]] = {base: [0.0, 0.0, 0.0]}
    for j in robot["joints"]:
        frame[j["child"]] = j["origin_mm"]
    out = ['<?xml version="1.0"?>', "<!--"]
    out += ["  " + x for x in _header(robot)]
    out += ["-->", f"<robot name={quoteattr(_name(robot['source']))}>"]
    wrote_note = False
    for link in robot["links"]:
        names = ", ".join(i["name"] for i in link["instances"])
        out.append(f"  <!-- {_c(link['id'])}: {_c(names)} -->")
        out.append(f"  <link name={quoteattr(link['id'])}>")
        if link["mass_g"] is not None:
            if not wrote_note:
                out.insert(
                    len(out) - 2,
                    "  <!-- mass and inertia are estimates from CAD volume and an assumed density -->",
                )
                wrote_note = True
            com = [c - o for c, o in zip(link["com_mm"], frame[link["id"]], strict=True)]
            i = link["inertia_g_mm2"]
            out += [
                "    <inertial>",
                f'      <origin xyz="{_xyz(com)}" rpy="0 0 0"/>',
                f'      <mass value="{_n(link["mass_g"] * G)}"/>',
                "      <inertia "
                + " ".join(
                    f'{k}="{_n(v * INERTIA)}"'
                    for k, v in (
                        ("ixx", i[0][0]),
                        ("ixy", i[0][1]),
                        ("ixz", i[0][2]),
                        ("iyy", i[1][1]),
                        ("iyz", i[1][2]),
                        ("izz", i[2][2]),
                    )
                )
                + "/>",
                "    </inertial>",
            ]
        out.append("  </link>")
    for j in robot["joints"]:
        axis = list(j["axis"])
        notes = []
        if j["positive_direction"] == "cw" and j["type"] == "revolute":
            axis = [-x for x in axis]
            notes.append("positive direction cw: axis flipped")
        if j["positive_direction"] == "-" and j["type"] == "prismatic":
            axis = [-x for x in axis]
            notes.append("positive direction against the stored axis: axis flipped")
        lim = j["limits"]
        unknown = lim["lower"] is None
        jtype = "continuous" if unknown and j["type"] == "revolute" else j["type"]
        label = f"{j['id']} ({j['type']}, confidence {_n(j['confidence'])})"
        out.append(f"  <!-- {_c(label)}{_c('; ' + '; '.join(notes)) if notes else ''} -->")
        out.append(f"  <joint name={quoteattr('joint_' + j['id'])} type={quoteattr(jtype)}>")
        out += [
            f"    <parent link={quoteattr(j['parent'])}/>",
            f"    <child link={quoteattr(j['child'])}/>",
            f'    <origin xyz="{_xyz(j["origin_in_parent_mm"])}" rpy="0 0 0"/>',
            f'    <axis xyz="{" ".join(_n(x) for x in axis)}"/>',
        ]
        if lim["lower"] is not None:
            scale = math.pi / 180.0 if j["type"] == "revolute" else MM
            # the range is in the designer's positive direction, which the flipped axis makes positive
            lo, hi = lim["lower"] * scale, lim["upper"] * scale
            out.append(f'    <limit lower="{_n(lo)}" upper="{_n(hi)}" effort="0" velocity="0"/>')
        elif jtype == "continuous":
            out.append("    <!-- limits unknown; change to revolute and add a limit -->")
        else:  # a prismatic joint: URDF has no unlimited one, so a limit element is required
            out.append("    <!-- limits unknown; set lower and upper (metres) before use -->")
            out.append('    <limit effort="0" velocity="0"/>')
        out.append("  </joint>")
    out.append("</robot>")
    return "\n".join(out) + "\n"


def urdf_text(report: Report) -> str | None:
    """The draft URDF text, or None for a design with no revolute or prismatic joint."""
    robot = build_robot(report)
    return None if robot is None else build_urdf(robot)
