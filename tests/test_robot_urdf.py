def test_the_pack_contains_the_urdf_for_a_robot_only(tmp_path: Path, step_files) -> None:  # type: ignore[no-untyped-def]
    for name, expected in (("arm_6_axis", True), ("two_plates_assembly", False)):
        out = tmp_path / name
        res = CliRunner().invoke(
            app, ["pack", str(step_files[name]), "--out", str(out), "--no-images", "--no-timestamp"]
        )
        assert res.exit_code == 0, res.output
        assert bool(list(out.rglob("robot.urdf"))) is expected


