HEADER = "Draft generated by stepscribe from geometry. Needs human verification."


@pytest.fixture(scope="module")
def arm(step_files):  # type: ignore[no-untyped-def]
    return analyze_full(
        step_files["arm_6_axis"], AnalyzeOptions(no_timestamp=True, material="steel")
    ).report


def parse(text: str) -> ET.Element:
    return ET.fromstring(text)


def floats(s: str) -> list[float]:
    return [float(x) for x in s.split()]


def test_the_header_says_it_is_a_draft_that_needs_verification(arm) -> None:  # type: ignore[no-untyped-def]
    text = build_urdf(build_robot(arm))  # type: ignore[arg-type]
    assert text.startswith('<?xml version="1.0"?>')
    first_comment = text.split("<!--", 1)[1].split("-->", 1)[0]
    assert HEADER in first_comment
    assert "outer skins" in first_comment and "not reliable" in first_comment
    assert "vendor" not in first_comment.lower()
    assert "estimate" in first_comment


def test_the_structure_matches_robot_json(arm) -> None:  # type: ignore[no-untyped-def]
    robot = build_robot(arm)
    assert robot is not None
    root = parse(build_urdf(robot))
    links = root.findall("link")
    joints = root.findall("joint")
    assert root.tag == "robot" and len(links) == len(robot["links"]) == 7
    assert len(joints) == len(robot["joints"]) == 6
    names = [link.get("name") for link in links]
    assert len(set(names)) == 7
    for j, spec in zip(joints, robot["joints"], strict=True):
        # no designer limits in this run: a revolute joint with unknown limits is written continuous
        assert j.get("type") == ("continuous" if spec["type"] == "revolute" else spec["type"])
        assert j.find("parent").get("link") == spec["parent"]  # type: ignore[union-attr]
        assert j.find("child").get("link") == spec["child"]  # type: ignore[union-attr]
        assert floats(j.find("axis").get("xyz")) == pytest.approx(spec["axis"], abs=1e-6)  # type: ignore[union-attr]
        want = [v * 1e-3 for v in spec["origin_in_parent_mm"]]
        assert floats(j.find("origin").get("xyz")) == pytest.approx(want, abs=1e-9)  # type: ignore[union-attr]
        assert j.find("origin").get("rpy") == "0 0 0"  # type: ignore[union-attr]


def test_the_links_form_one_tree_from_the_base(arm) -> None:  # type: ignore[no-untyped-def]
    robot = build_robot(arm)
    assert robot is not None
    root = parse(build_urdf(robot))
    children = [j.find("child").get("link") for j in root.findall("joint")]  # type: ignore[union-attr]
    names = {link.get("name") for link in root.findall("link")}
    assert len(children) == len(set(children))  # one parent joint per link
    assert names - set(children) == {robot["base_link"]}  # only the base has no parent joint
    parents = {
        j.find("child").get("link"): j.find("parent").get("link") for j in root.findall("joint")
    }  # type: ignore[union-attr]
    for child in children:  # every link reaches the base
        seen, cur = set(), child
        while cur != robot["base_link"]:
            assert cur not in seen
            seen.add(cur)
            cur = parents[cur]


def test_masses_are_kilograms_and_marked_as_estimates(arm) -> None:  # type: ignore[no-untyped-def]
    robot = build_robot(arm)
    assert robot is not None
    root = parse(build_urdf(robot))
    for link, spec in zip(root.findall("link"), robot["links"], strict=True):
        inertial = link.find("inertial")
        assert inertial is not None
        assert float(inertial.find("mass").get("value")) == pytest.approx(
            spec["mass_g"] * 1e-3, rel=1e-6
        )  # type: ignore[union-attr]
        ixx = float(inertial.find("inertia").get("ixx"))  # type: ignore[union-attr]
        assert ixx == pytest.approx(spec["inertia_g_mm2"][0][0] * 1e-9, rel=1e-5)
    assert "<!-- mass and inertia are estimates" in build_urdf(robot)


