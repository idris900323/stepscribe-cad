def test_limits_are_only_written_when_the_designer_gave_them(step_files, tmp_path) -> None:  # type: ignore[no-untyped-def]
    yaml_path = tmp_path / "design_context.yaml"
    yaml_path.write_text(
        "kinematics:\n  joints:\n    - between: [LINK1, LINK2]\n      axis: '+Y'\n      range: [-90, 110]\n",
        encoding="utf-8",
    )
    opts = AnalyzeOptions(no_timestamp=True, material="steel")
    apply_context(opts, load_context(yaml_path))
    robot = build_robot(analyze_full(step_files["arm_6_axis"], opts).report)
    assert robot is not None
    # URDF: a revolute joint needs a <limit> with effort and velocity, and lower/upper default to 0
    # (a locked joint). With no known limits the honest type is `continuous`; given ones stay revolute.
    root = parse(build_urdf(robot))
    joints = root.findall("joint")
    assert [j.get("type") for j in joints] == [
        "continuous",
        "revolute",
        "continuous",
        "continuous",
        "continuous",
        "continuous",
    ]
    known = joints[1].find("limit")
    assert known is not None
    assert float(known.get("lower")) == pytest.approx(math.radians(-90), abs=1e-6)  # type: ignore[arg-type]
    assert float(known.get("upper")) == pytest.approx(math.radians(110), abs=1e-6)  # type: ignore[arg-type]
    assert known.get("effort") is not None and known.get("velocity") is not None
    for j in joints:
        if j.get("type") == "continuous":
            assert j.find("limit") is None  # nothing invented
    text = build_urdf(robot)
    assert text.count("limits unknown; change to revolute and add a limit") == 5


def test_a_prismatic_joint_without_limits_stays_prismatic_with_a_comment() -> None:
    robot = {
        "source": "slide",
        "base_link": "L0",
        "warnings": [],
        "dh_style": {"rows": []},
        "links": [
            {"id": "L0", "instances": [{"id": "INS001", "name": "RAIL"}], "mass_g": None},
            {"id": "L1", "instances": [{"id": "INS002", "name": "CARRIAGE"}], "mass_g": None},
        ],
        "joints": [
            {
                "id": "KJ1",
                "type": "prismatic",
                "parent": "L0",
                "child": "L1",
                "axis": [1.0, 0.0, 0.0],
                "origin_mm": [0.0, 0.0, 0.0],
                "origin_in_parent_mm": [0.0, 0.0, 0.0],
                "limits": {"lower": None, "upper": None, "unit": "mm", "source": "unknown"},
                "positive_direction": None,
                "confidence": 0.6,
            }
        ],
    }
    text = build_urdf(robot)
    (j,) = parse(text).findall("joint")
    assert j.get("type") == "prismatic"  # URDF has no unlimited prismatic joint
    assert "limits unknown" in text and 'effort="0" velocity="0"' in text


def test_a_clockwise_positive_joint_has_its_axis_flipped(step_files, tmp_path) -> None:  # type: ignore[no-untyped-def]
    yaml_path = tmp_path / "design_context.yaml"
    yaml_path.write_text(
        "kinematics:\n  joints:\n    - between: [LINK1, LINK2]\n      positive: cw\n",
        encoding="utf-8",
    )
    opts = AnalyzeOptions(no_timestamp=True)
    apply_context(opts, load_context(yaml_path))
    robot = build_robot(analyze_full(step_files["arm_6_axis"], opts).report)
    assert robot is not None
    baseline = build_robot(
        analyze_full(step_files["arm_6_axis"], AnalyzeOptions(no_timestamp=True)).report
    )
    assert baseline is not None
    root = parse(build_urdf(robot))
    j2 = root.findall("joint")[1]
    # robot.json already holds the flipped arrow; the URDF carries it once, not twice
    assert floats(j2.find("axis").get("xyz")) == pytest.approx(robot["joints"][1]["axis"])  # type: ignore[union-attr]
    assert robot["joints"][1]["axis"] == pytest.approx([-v for v in baseline["joints"][1]["axis"]])
    assert "positive direction cw: axis flipped" in build_urdf(robot)


